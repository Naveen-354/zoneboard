import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

let timezones = Intl.supportedValuesOf('timeZone');
// Node's ICU returns legacy 'Asia/Calcutta'; replace with canonical IANA name 'Asia/Kolkata'
timezones = timezones.map(tz => (tz === 'Asia/Calcutta' ? 'Asia/Kolkata' : tz));
if (!timezones.includes('UTC')) {
  timezones.push('UTC');
}

// Sort by Unicode code point (exact match for Rust's &str Ord / binary search) and deduplicate
const uniqueSorted = Array.from(new Set(timezones)).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const outPath = path.resolve(__dirname, '../src-tauri/src/timezones.rs');

const header = `// Generated by 'node tools/gen_timezones.mjs' with Node ${process.version}. Do not edit by hand.
// Canonical IANA timezone names only; aliases such as 'Asia/Calcutta' are rejected.

pub static CANONICAL: &[&str] = &[
${uniqueSorted.map(tz => `    "${tz}",`).join('\n')}
];

/// Returns true if \`tz\` is a canonical IANA timezone name.
///
/// Canonical names only; aliases such as \`Asia/Calcutta\` are rejected.
pub fn is_valid_timezone(tz: &str) -> bool {
    CANONICAL.binary_search(&tz).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn timezone_list_is_sorted_and_unique() {
        assert!(
            CANONICAL.windows(2).all(|w| w[0] < w[1]),
            "CANONICAL timezones must be strictly sorted and unique for binary search"
        );
    }

    #[test]
    fn canonical_timezones_include_required_names() {
        assert!(is_valid_timezone("UTC"));
        assert!(is_valid_timezone("Asia/Kolkata"));
        assert!(is_valid_timezone("America/New_York"));
        assert!(is_valid_timezone("Europe/London"));
    }

    #[test]
    fn invalid_timezones_are_rejected() {
        assert!(!is_valid_timezone("Mars/Olympus"));
        assert!(!is_valid_timezone("EST"));
        assert!(!is_valid_timezone(""));
        assert!(!is_valid_timezone("asia/kolkata")); // case matters
        assert!(!is_valid_timezone("Asia/Calcutta")); // alias rejected
    }
}
`;

fs.writeFileSync(outPath, header, 'utf8');
console.log(`Generated ${uniqueSorted.length} timezones to ${outPath}`);
