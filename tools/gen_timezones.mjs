import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const TZDATA_VERSION = '2026.2';

const zoneTabPath = path.resolve(__dirname, 'data/zone.tab');
const zoneTabContent = fs.readFileSync(zoneTabPath, 'utf8');
const zoneTabNames = zoneTabContent
  .split('\n')
  .map(line => line.trim())
  .filter(line => line.length > 0 && !line.startsWith('#'))
  .map(line => line.split('\t')[2].trim());

const nodeTimezones = Intl.supportedValuesOf('timeZone');

const allTimezones = [...zoneTabNames, ...nodeTimezones, 'UTC'];

// Sort by Unicode code point (exact match for Rust's &str Ord / binary search) and deduplicate
const uniqueSorted = Array.from(new Set(allTimezones)).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

// Assert every name is accepted by Intl.DateTimeFormat
const invalidNames = [];
for (const tz of uniqueSorted) {
  try {
    new Intl.DateTimeFormat('en', { timeZone: tz });
  } catch (_e) {
    invalidNames.push(tz);
  }
}
if (invalidNames.length > 0) {
  throw new Error(`Invalid timezone names encountered: ${invalidNames.join(', ')}`);
}

const outPath = path.resolve(__dirname, '../src-tauri/src/timezones.rs');

const header = `// Generated by 'node tools/gen_timezones.mjs' with Node ${process.version} and tzdata ${TZDATA_VERSION}. Do not edit by hand.
// IANA zone.tab names plus the names browsers report (ICU).

pub static CANONICAL: &[&str] = &[
${uniqueSorted.map(tz => `    "${tz}",`).join('\n')}
];

/// Returns true if \`tz\` is a valid timezone name (in IANA zone.tab or reported by browsers).
pub fn is_valid_timezone(tz: &str) -> bool {
    CANONICAL.binary_search(&tz).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn timezone_list_is_sorted_and_unique() {
        assert!(
            CANONICAL.windows(2).all(|w| w[0] < w[1]),
            "CANONICAL timezones must be strictly sorted and unique for binary search"
        );
    }

    #[test]
    fn canonical_timezones_include_required_names() {
        let accepted = [
            "UTC",
            "Asia/Kolkata",
            "Asia/Calcutta",
            "Europe/Kyiv",
            "Europe/Kiev",
            "Asia/Kathmandu",
            "Asia/Katmandu",
            "America/Argentina/Buenos_Aires",
            "America/Buenos_Aires",
            "America/New_York",
            "Europe/London",
        ];
        for tz in accepted {
            assert!(is_valid_timezone(tz), "expected {tz} to be accepted");
        }
    }

    #[test]
    fn invalid_timezones_are_rejected() {
        let rejected = [
            "Mars/Olympus",
            "EST",
            "US/Eastern",
            "",
            "asia/kolkata", // case matters
        ];
        for tz in rejected {
            assert!(!is_valid_timezone(tz), "expected {tz} to be rejected");
        }
    }
}
`;

fs.writeFileSync(outPath, header, 'utf8');
console.log(`Generated ${uniqueSorted.length} timezones to ${outPath}`);
